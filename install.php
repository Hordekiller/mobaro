error_reporting(E_ALL);
ini_set('display_errors', '1');

$baseDir = __DIR__;
$envPath = $baseDir . '/.env';
$lockPath = $baseDir . '/install.lock';

$alreadyInstalled = false;
if (is_file($envPath)) {
    $envContent = (string) file_get_contents($envPath);
    $alreadyInstalled = str_contains($envContent, 'DB_NAME=') && preg_match('/^DB_NAME=.+/m', $envContent) === 1;
}

$steps = ['info', 'form', 'done'];
$step = $_GET['step'] ?? 'form';
if ($alreadyInstalled && ($step === 'form' || $step === 'info')) {
    $step = 'done';
}
if (!in_array($step, $steps, true)) {
    $step = 'form';
}

$error = '';
