function normalizePhone(string $phone): string
{
    $phone = trim($phone);
    $phone = preg_replace('/[^\d+]/', '', $phone);
    if (str_starts_with($phone, '+98')) {
        $phone = '0' . substr($phone, 3);
    } elseif (str_starts_with($phone, '98')) {
        $phone = '0' . substr($phone, 2);
    }
    return $phone;
}

function writeEnvFile(string $path, array $values): bool
{
    $content = "# Auto-generated by install.php — edit safely after install\n"
        . "APP_NAME=" . ($values['app_name'] ?? 'موبارو') . "\n"
        . "APP_URL=" . rtrim((string) ($values['app_url'] ?? ''), '/') . "\n"
        . "APP_ENV=production\n"
        . "APP_DEBUG=false\n\n"
        . "DB_HOST=" . ($values['db_host'] ?? 'localhost') . "\n"
        . "DB_NAME=" . ($values['db_name'] ?? '') . "\n"
        . "DB_USER=" . ($values['db_user'] ?? '') . "\n"
        . "DB_PASS=" . ($values['db_pass'] ?? '') . "\n"
        . "DB_CHARSET=" . ($values['db_charset'] ?? 'utf8mb4') . "\n\n"
        . "CACHE_PREFIX=mobaro\n"
        . "CACHE_DIR=\n"
        . "CACHE_TTL_DEFAULT=3600\n"
        . "CACHE_TTL_PAGE=600\n"
        . "CACHE_TTL_ADMIN=300\n\n"
        . "ZARINPAL_MERCHANT_ID=\n"
        . "ZARINPAL_SANDBOX=true\n\n"
        . "GOOGLE_CLIENT_ID=\n"
        . "GOOGLE_CLIENT_SECRET=\n"
        . "GOOGLE_REDIRECT_URI=" . rtrim((string) ($values['app_url'] ?? ''), '/') . "/auth/google/callback\n\n"
        . "# SMS (sms.ir)\n"
        . "SMS_ENABLED=false\n"
        . "SMS_API_KEY=\n"
        . "SMS_TEMPLATE_ID=\n"
        . "SMS_LINE_NUMBER=\n"
        . "SMS_OTP_TTL=180\n"
        . "SMS_OTP_LENGTH=5\n\n"
        . "# TinyMCE\n"
        . "TINYMCE_API_KEY=no-api-key\n";

    return file_put_contents($path, $content, LOCK_EX) !== false;
}

function execSqlFile(PDO $pdo, string $file): array
{
    $messages = [];
    $sql = file_get_contents($file);
    if ($sql === false) {
        return ['[خطا] فایل ' . basename($file) . ' پیدا نشد.'];
    }

    // Strip full-line comments first so a statement chunk never begins with them.
    $lines = array_filter(
        explode("\n", $sql),
        fn(string $l): bool => !str_starts_with(ltrim($l), '--') && !str_starts_with(ltrim($l), '/*')
    );
    $sql = implode("\n", $lines);

    $statements = array_filter(
        array_map('trim', explode(';', $sql)),
        fn(string $s): bool => $s !== ''
            && !str_starts_with($s, '--') && !str_starts_with($s, '/*')
            && !str_starts_with($s, 'CREATE DATABASE') && !str_starts_with($s, 'USE ')
            && !str_starts_with($s, 'DELIMITER')
    );

    foreach ($statements as $stmt) {
        $pdo->exec($stmt);
    }
    $messages[] = '[OK] ' . basename($file) . ' اجرا شد (' . count($statements) . ' دستور).';
    return $messages;
}

if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST' && $step === 'form') {
    if ($alreadyInstalled) {
        $step = 'done';
    } else {
        $dbHost = trim((string) ($_POST['db_host'] ?? ''));
        $dbName = trim((string) ($_POST['db_name'] ?? ''));
        $dbUser = trim((string) ($_POST['db_user'] ?? ''));
        $dbPass = (string) ($_POST['db_pass'] ?? '');
        $dbCharset = trim((string) ($_POST['db_charset'] ?? 'utf8mb4'));
        $appName = trim((string) ($_POST['app_name'] ?? ''));
        $appUrl = trim((string) ($_POST['app_url'] ?? ''));
        $phone = normalizePhone((string) ($_POST['phone'] ?? ''));
        $password = (string) ($_POST['password'] ?? '');
        $password2 = (string) ($_POST['password2'] ?? '');
        $withSeed = isset($_POST['with_seed']);
        $createDb = isset($_POST['create_db']);

        if ($dbHost === '' || $dbName === '' || $dbUser === '') {
            $error = 'مشخصات دیتابیس (host، name و user) اجباری است.';
        } elseif ($appName === '' || $appUrl === '') {
            $error = 'نام سایت و آدرس دامنه اجباری است.';
        } elseif ($phone === '' || !preg_match('/^09\d{9}$/', $phone)) {
            $error = 'شماره موبایل معتبر نیست (مثال: ۰۹۱۲۳۴۵۶۷۸۹).';
        } elseif (strlen($password) < 6) {
            $error = 'رمز عبور باید حداقل ۶ کاراکتر باشد.';
        } elseif ($password !== $password2) {
            $error = 'رمز عبور و تکرار آن یکسان نیستند.';
        } else {
            try {
                $dsn = "mysql:host={$dbHost};charset={$dbCharset}";
                $db = new PDO($dsn, $dbUser, $dbPass, [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                ]);

                if ($createDb) {
                    $db->exec(
                        "CREATE DATABASE IF NOT EXISTS `" . str_replace('`', '', $dbName)
                        . "` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"
                    );
                }

                $db->exec("USE `" . str_replace('`', '', $dbName) . "`");

                if (!is_writable($baseDir)) {
                    throw new RuntimeException('پوشه اصلی قابل نوشتن نیست (برای ساخت .env).');
                }

                $messages = execSqlFile($db, $baseDir . '/database/schema.sql');

                $hashed = password_hash($password, PASSWORD_BCRYPT);
                $stmt = $db->prepare(
                    "INSERT INTO users (name, family, phone, password, role, is_active)
                     VALUES ('مدیر', 'سیستم', ?, ?, 'admin', 1)
                     ON DUPLICATE KEY UPDATE password = VALUES(password)"
                );
                $stmt->execute([$phone, $hashed]);
                $messages[] = '[OK] حساب مدیر ساخته شد.';

                if ($withSeed) {
                    $seedMessages = execSqlFile($db, $baseDir . '/database/seed.sql');
                    $messages = array_merge($messages, $seedMessages);
                    $db->exec("DELETE FROM users WHERE role = 'admin' AND phone <> " . $db->quote($phone));
                }

                writeEnvFile($envPath, [
                    'app_name' => $appName,
                    'app_url' => $appUrl,
                    'db_host' => $dbHost,
                    'db_name' => $dbName,
                    'db_user' => $dbUser,
                    'db_pass' => $dbPass,
                    'db_charset' => $dbCharset,
                ]);

                @file_put_contents($lockPath, date('c'), LOCK_EX);

                $step = 'done';
                $_SESSION = [];
            } catch (PDOException $e) {
                $error = 'خطای دیتابیس: ' . htmlspecialchars($e->getMessage());
            } catch (Throwable $e) {
                $error = 'خطا: ' . htmlspecialchars($e->getMessage());
            }
        }
    }
}
